// Builds site/app/gtha-transit-data.js from two extracts:
//   geo.json   { stationId: [lat, lon] } for every template station, from OpenStreetMap
//   viva.json  VIVA routes from the York Region Transit GTFS feed: name, colour, peak and midday
//              headways in minutes, and the ordered stops of the busiest pattern
// Usage: node scripts/data/make-transit-data.mjs <geo.json> <viva.json>
// See scripts/data/README.md for how the extracts were produced.
import fs from 'node:fs';
import vm from 'node:vm';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const [geoFile, vivaFile] = process.argv.slice(2);
const GEO = JSON.parse(fs.readFileSync(geoFile, 'utf8'));
const VIVA = JSON.parse(fs.readFileSync(vivaFile, 'utf8'));
const ctx = { window: {} }; vm.createContext(ctx);
vm.runInContext(fs.readFileSync(path.join(root, 'site/app/gtha-template.js'), 'utf8'), ctx);
const tpl = ctx.window.GTHATemplates.gtha();

const R = 6378137;
const merc = (lat, lon) => [R * lon * Math.PI / 180, R * Math.log(Math.tan(Math.PI / 4 + lat * Math.PI / 360))];
const dist = (a, b) => { const p = merc(...a), q = merc(...b); return Math.hypot(p[0] - q[0], p[1] - q[1]) * Math.cos(a[0] * Math.PI / 180); };

// Least-squares affine fit from Web Mercator metres to schematic grid units, so stops that only
// have real coordinates still get a sensible schematic position.
function fit(axis) {
  const rows = Object.entries(GEO).filter(([id]) => tpl.stations[id]).map(([id, ll]) => { const [mx, my] = merc(...ll); return [mx / 1000, my / 1000, 1, tpl.stations[id][axis]]; });
  const A = [[0, 0, 0], [0, 0, 0], [0, 0, 0]], b = [0, 0, 0];
  for (const r of rows) for (let i = 0; i < 3; i++) { b[i] += r[i] * r[3]; for (let j = 0; j < 3; j++) A[i][j] += r[i] * r[j]; }
  for (let i = 0; i < 3; i++) { let p = i; for (let k = i + 1; k < 3; k++) if (Math.abs(A[k][i]) > Math.abs(A[p][i])) p = k; [A[i], A[p]] = [A[p], A[i]]; [b[i], b[p]] = [b[p], b[i]];
    for (let k = i + 1; k < 3; k++) { const f = A[k][i] / A[i][i]; for (let j = i; j < 3; j++) A[k][j] -= f * A[i][j]; b[k] -= f * b[i]; } }
  const x = [0, 0, 0]; for (let i = 2; i >= 0; i--) { let s = b[i]; for (let j = i + 1; j < 3; j++) s -= A[i][j] * x[j]; x[i] = s / A[i][i]; }
  return x;
}
const fx = fit('x'), fy = fit('y');
const toGrid = (ll) => { const [mx, my] = merc(...ll); return [Math.round((fx[0] * mx / 1000 + fx[1] * my / 1000 + fx[2]) * 2) / 2, Math.round((fy[0] * mx / 1000 + fy[1] * my / 1000 + fy[2]) * 2) / 2]; };

const titleCase = (s) => s.toLowerCase().replace(/\b([a-z])/g, (c) => c.toUpperCase()).replace(/\bGo\b/g, 'GO').replace(/\bHwy\b/g, 'Hwy').replace(/\s+Platform\s+\d+$/i, '').replace(/\s+(Westbound|Eastbound|Northbound|Southbound)$/i, '').trim();
const slug = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, '_').replace(/^_|_$/g, '');
const ROUTES = [['601', 'viva_blue', 'Viva Blue', 'Viva 藍線'], ['603', 'viva_purple', 'Viva Purple', 'Viva 紫線'], ['605', 'viva_orange', 'Viva Orange', 'Viva 橙線'], ['607', 'viva_yellow', 'Viva Yellow', 'Viva 黃線']];
const stops = {}, lines = [];
for (const [rid, id, name, nameZh] of ROUTES) {
  const r = VIVA[rid]; if (!r) throw new Error('missing route ' + rid);
  const pathIds = [];
  for (const [rawName, lat, lon] of r.stops) {
    const ll = [lat, lon];
    let near = null, best = 300;
    for (const [sid, g] of Object.entries(GEO)) { const d = dist(ll, g); if (d < best) { best = d; near = sid; } }
    if (!near) for (const [sid, s] of Object.entries(stops)) { const d = dist(ll, [s.lat, s.lon]); if (d < 120) { near = sid; break; } }
    if (!near) {
      const nm = titleCase(rawName); let sid = 'viva_' + slug(nm); let n = 2; while (stops[sid] && dist(ll, [stops[sid].lat, stops[sid].lon]) > 120) sid = 'viva_' + slug(nm) + '_' + n++;
      if (!stops[sid]) { const [x, y] = toGrid(ll); stops[sid] = { name: nm, lat, lon, x, y }; }
      near = sid;
    }
    if (pathIds[pathIds.length - 1] !== near) pathIds.push(near);
  }
  lines.push({ id, name, nameZh, color: r.color.toUpperCase(), style: 'brt', width: 6, path: pathIds, freq: { peak: r.peak, offpeak: r.midday }, showFreq: true,
    note: 'Stops and weekday frequencies from the York Region Transit GTFS feed, 1 November to 19 December 2026.' });
}
// nudge stacked schematic positions apart
const used = new Set(Object.values(tpl.stations).map((s) => s.x + ',' + s.y));
for (const s of Object.values(stops)) { let k = 0; while (used.has(s.x + ',' + s.y) && k < 8) { s.x += 0.5; k++; } used.add(s.x + ',' + s.y); }

const out = `// Generated by scripts/data/make-transit-data.mjs. Do not edit by hand.
// Station coordinates: OpenStreetMap contributors (ODbL). VIVA routes, stops and frequencies:
// York Region Transit GTFS feed, service 1 November to 19 December 2026.
(function () {
  'use strict';
  window.GTHATransitData = ${JSON.stringify({ geo: GEO, stops, lines })};
})();
`;
fs.writeFileSync(path.join(root, 'site/app/gtha-transit-data.js'), out);
console.log('stations with coordinates', Object.keys(GEO).length, 'new stops', Object.keys(stops).length, 'lines', lines.map((l) => l.id + ':' + l.path.length).join(' '));
